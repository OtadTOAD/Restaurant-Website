import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const publicDir = fileURLToPath(new URL('../public/', import.meta.url));
const output = fileURLToPath(new URL('../src/app/config/asset-version.ts', import.meta.url));
const hash = createHash('sha256');

async function visit(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name, 'en'));

  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      await visit(path);
    } else if (entry.isFile()) {
      hash.update(relative(publicDir, path));
      hash.update('\0');
      hash.update(await readFile(path));
      hash.update('\0');
    }
  }
}

await visit(publicDir);
const version = hash.digest('hex').slice(0, 16);
const source = `// Generated by scripts/generate-asset-version.mjs.\nexport const ASSET_VERSION = '${version}';\n`;
let previous;
try {
  previous = await readFile(output, 'utf8');
} catch {
  // First build.
}
if (previous !== source) {
  await writeFile(output, source);
}
console.log(`Asset version: ${version}`);
